// ข้อความที่เป็นการ "ตอบรับ / ปิดบทสนทนา" ล้วนๆ เช่น "ค่ะ" "ได้ค่ะ" "รับทราบ" "โอเค" "ขอบคุณค่ะ"
// บอทไม่ควรตอบข้อความแบบนี้ โดยเฉพาะตอนลูกค้าตอบกลับที่ที่ร้าน (คนจริง) พิมพ์ไปก่อน
// (บอทไม่เห็นข้อความที่เจ้าของพิมพ์ จะเข้าใจว่าเป็นลูกค้าใหม่แล้วทักต้อนรับแทรกขึ้นมา)

const ACK_WORDS = [
  'ค่ะ', 'คะ', 'ค่า', 'คา', 'จ้า', 'จ้ะ', 'ครับ', 'คับ', 'ครับผม', 'คับผม', 'ครับบ', 'ค่ะะ', 'คร้าบ',
  'ได้', 'ได้เลย', 'ได้จ้า', 'ได้ค่ะ', 'ได้คะ', 'ได้ครับ', 'ได้คับ', 'ได้เลยค่ะ', 'ได้เลยครับ', 'ได้เลยคับ',
  'โอเค', 'โอเคค่ะ', 'โอเคครับ', 'โอเคคับ', 'โอเคจ้า', 'โอเคนะ', 'ok', 'okay', 'oky', 'okค่ะ', 'okครับ',
  'ทราบแล้วค่ะ', 'ทราบแล้วครับ', 'ทราบแล้วคับ',
  'รับทราบ', 'รับทราบค่ะ', 'รับทราบครับ', 'รับทราบคับ', 'ทราบ', 'ทราบแล้ว', 'ทราบค่ะ', 'ทราบครับ', 'ทราบคับ',
  'เข้าใจแล้ว', 'เข้าใจค่ะ', 'เข้าใจครับ', 'เรียบร้อย', 'เรียบร้อยค่ะ', 'เรียบร้อยครับ',
  'ขอบคุณ', 'ขอบคุณค่ะ', 'ขอบคุณครับ', 'ขอบคุณคับ', 'ขอบคุณมาก', 'ขอบคุณมากค่ะ', 'ขอบคุณมากครับ', 'ขอบคุณมากคับ',
  'ขอบใจ', 'ขอบคุณนะคะ', 'ขอบคุณนะครับ', 'ขอบคุณนะ',
  'thanks', 'thankyou', 'thx', 'thankyouverymuch', 'gotit', 'noted',
]
const ACK_SET = new Set(ACK_WORDS)

// อีโมจิ/สัญลักษณ์ (ไม่ใช้แฟล็ก u เพราะ target ของโปรเจกต์ไม่รองรับ — จับด้วยช่วง surrogate + สัญลักษณ์ทั่วไป)
const EMOJI_RE = /[\uD800-\uDBFF][\uDC00-\uDFFF]|[←-⯿️‍]/g

// ตัดช่องว่าง เครื่องหมาย และอีโมจิ ก่อนเทียบ
function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/[\s​]+/g, '')
    .replace(/[!?.,:;'"“”‘’()\-_~…ฯ]/g, '')
    .replace(EMOJI_RE, '')
}

export function isAckMessage(text: string): boolean {
  const n = normalize(text)
  if (!n) return text.trim().length > 0 // เหลือแต่อีโมจิ/สัญลักษณ์ เช่น 👍 🙏 (ข้อความว่างจริงๆ ไม่นับ)
  if (/^5{2,}$/.test(n)) return true // 555
  if (ACK_SET.has(n)) return true
  // ลดตัวอักษรซ้ำท้ายคำ ("ค่าาา" → "ค่า", "okkk" → "ok")
  return ACK_SET.has(n.replace(/(.)\1+$/, '$1'))
}

// ข้อความที่เป็นการ "ขอบคุณ" โดยเฉพาะ (ตอบกลับว่า "ยินดีครับ") ส่วนข้อความตอบรับอื่น ตอบ "ขอบคุณครับ"
export function isThanksMessage(text: string): boolean {
  return isAckMessage(text) && /ขอบ|thank|thx/.test(normalize(text))
}
